-- envisia-forge auth realms slice (12.7): drop the SSRF private-range
-- restriction (design doc 2026-06-03, §3.6).
--
-- The per-proxy `allow_private_upstream` opt-out existed only to punch holes in
-- the slice-1 SSRF guard (private/loopback/link-local ranges blocked unless the
-- flag was set). Per the 12.7 decision the restriction is dropped entirely:
-- outbound proxy / credential-forwarding connections now enforce only an
-- http/https *scheme* check. Configuring upstream URLs is an **admin-only**
-- capability (RBAC `can_admin`), so the residual risk — an admin pointing forge
-- at an internal address — is a deliberate, documented trade-off; there is no
-- flag left to keep.
ALTER TABLE repository DROP COLUMN allow_private_upstream;
