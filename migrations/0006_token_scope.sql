-- envisia-forge fine-grained RBAC (slice 12.4), phase 3: per-token scoping.
--
-- Builds on 0001_init.sql (token) and 0005_rbac.sql (the RBAC tables). ADDITIVE
-- schema only: it adds a single nullable column. No behavior flips here —
--   * a NULL `scope` (the default for every existing token) means the token
--     inherits the FULL effective set of its owner (slice-1 behavior preserved),
--   * a non-NULL `scope` narrows the token to a subset of its owner's grants.
--
-- The scope is applied in code AFTER the (per-user) effective-set cache lookup
-- so the owner's cached set stays shared across all of that user's tokens — a
-- token can only ever intersect (never widen) its owner's grants.
--
-- Shape (validated in Rust as `forge_core::authz::TokenScope`):
--   { "actions": ["read", ...], "repositories": [<repository.id>, ...] }
-- An omitted "actions" key ⇒ all of the owner's actions; an omitted
-- "repositories" key ⇒ all repos the owner can touch. `{}` therefore equals NULL
-- (no narrowing). A malformed scope is rejected at deserialize time and the
-- evaluator fails closed (the token is treated as carrying no usable grants).
--
-- Multi-instance correctness: a plain column add; no pg_advisory_*; no
-- in-memory-only state.

ALTER TABLE token ADD COLUMN scope jsonb NULL;
