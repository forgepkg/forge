-- ---------------------------------------------------------------------------
-- apt repositories (#176): signing keys, index generations, and files that
-- never change.
-- ---------------------------------------------------------------------------

-- A file that never changes at its path: a proxy's copy of an upstream
-- package or content-addressed index (apt's `pool/` and `by-hash/`), which
-- is never re-validated, and a hosted repository's content-addressed index
-- file, which outlives the index that named it by a day (`checked_at`: when
-- an index last named it).
ALTER TABLE raw_file ADD COLUMN immutable boolean NOT NULL DEFAULT false;

-- ---------------------------------------------------------------------------
-- repository_signing_key: the OpenPGP keys that sign a repository's indexes
--
-- A repository of a format that keeps signed indexes (apt) has one key from
-- its creation, generated by Forge or imported. Every key of a repository
-- signs: during a rollover a repository has two, its clients trust either,
-- and the older is deleted once they all trust the newer.
--
-- `secret_key_enc` is the ASCII-armored transferable secret key, without a
-- passphrase, sealed with the secret encryption (`[crypto]`) and AAD-bound
-- to ('repository_signing_key', 'secret_key_enc', <row id>) and the key's
-- fingerprint. It never leaves the server.
-- ---------------------------------------------------------------------------
CREATE TABLE repository_signing_key (
    id              bigint      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    repository_id   bigint      NOT NULL REFERENCES repository(id) ON DELETE CASCADE,
    -- The primary key's fingerprint, uppercase hex.
    fingerprint     text        NOT NULL,
    -- The signing key's algorithm, for display (`EdDSA`, `RSA 4096`).
    algorithm       text        NOT NULL,
    -- The key's primary user id, for display.
    user_id         text        NOT NULL,
    -- The ASCII-armored certificate (public key).
    public_key      text        NOT NULL,
    secret_key_enc  bytea,
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (repository_id, fingerprint)
);

CREATE INDEX repository_signing_key_repository_idx ON repository_signing_key (repository_id);

-- ---------------------------------------------------------------------------
-- repository_index: the index generation a repository serves
--
-- The files of a repository's indexes are `raw_file` rows of the repository.
-- `fingerprint` digests what they were made of (the listed versions, the
-- options, the signing keys, the format's version): a client's request for
-- an index whose fingerprint no longer matches makes a new generation, which
-- replaces the files all at once.
-- ---------------------------------------------------------------------------
CREATE TABLE repository_index (
    repository_id   bigint      PRIMARY KEY REFERENCES repository(id) ON DELETE CASCADE,
    fingerprint     text        NOT NULL,
    generated_at    timestamptz NOT NULL DEFAULT now()
);
